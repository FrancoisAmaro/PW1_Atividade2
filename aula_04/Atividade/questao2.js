// Arrow function

/* Uma arrow function é uma sintaxe mais curta e moderna (introduzida no ES6) para escrever expressões 
de função, que não possui seu próprio this, arguments ou super. Não utiliza a palavra-chave function, 
utiliza a flecha => e permite retorno implícito quando o corpo não usa chaves {}.*/


const soma = (a, b) => a + b;



